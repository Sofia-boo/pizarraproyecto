import {chromium,expect} from '@playwright/test'
import {writeFile} from 'node:fs/promises'
// Explicit, heavyweight smoke test: downloads ~890 MB on its first run.
// It uses a separate browser profile and simulated APIs; real boards are untouched.
const context=await chromium.launchPersistentContext('logs/ia-prueba-browser',{channel:'chrome',headless:true,viewport:{width:1366,height:900}})
context.setDefaultTimeout(20000)
try{
  await context.route('**/api/**',r=>r.fulfill({status:503,body:'offline'}))
  const page=await context.newPage()
  page.on('pageerror',e=>console.log('PAGE ERROR',e.message))
  page.on('console',m=>{if(m.type()==='error'||m.type()==='warning')console.log(m.type(),m.text().slice(0,1200))})
  page.on('requestfailed',r=>console.log('FAILED',new URL(r.url()).pathname,r.failure()?.errorText))
  await page.goto('http://127.0.0.1:4173')
  await page.evaluate(async()=>{
    for(const registration of await navigator.serviceWorker.getRegistrations())await registration.unregister()
    for(const key of await caches.keys())if(key.startsWith('pizarra-app-'))await caches.delete(key)
    const db=await new Promise(resolve=>{const r=indexedDB.open('pizarra-dispositivo',1);r.onsuccess=()=>resolve(r.result)})
    await new Promise(resolve=>{const tx=db.transaction('meta','readwrite');const r=tx.objectStore('meta').getAllKeys();r.onsuccess=()=>{for(const key of r.result)if(String(key).startsWith('assistant:'))tx.objectStore('meta').delete(key)};tx.oncomplete=resolve});db.close()
  })
  await page.reload()
  const local=page.getByRole('button',{name:'Abrir privadas y copias de este dispositivo'})
  if(await local.count())await local.click()
  await expect(page.locator('.library-open-button')).toContainText('privada')
  await page.getByRole('button',{name:'IA: opciones de reconocimiento',exact:true}).click()
  await page.getByRole('menuitem',{name:/Asistente de estudio local/}).click()
  let dialog=page.getByRole('dialog',{name:'Asistente de estudio local'})
  await dialog.getByRole('button',{name:/Cargar IA guardada|Descargar IA para/}).click()
  const timer=setInterval(async()=>console.log('ESTADO',(await dialog.innerText().catch(()=>'' )).slice(-700)),15000)
  try{await Promise.race([expect(dialog.getByRole('status')).toHaveText('IA lista',{timeout:300000}),dialog.getByRole('alert').waitFor({timeout:300000}).then(async()=>{throw new Error(await dialog.getByRole('alert').innerText())})])}finally{clearInterval(timer)}
  console.log('MODELO CARGADO')
  await context.setOffline(true)
  await page.getByRole('textbox',{name:'Pregunta al asistente'}).fill('¿Cuánto es 2 + 3? Respondé brevemente.')
  const start=Date.now()
  await dialog.getByRole('button',{name:'Preguntar',exact:true}).click()
  await expect(dialog.getByRole('button',{name:'Detener respuesta'})).toHaveCount(0,{timeout:180000})
  const answer=await dialog.locator('.assistant-message.assistant .assistant-answer').last().innerText()
  console.log('RESPUESTA',answer,'SEGUNDOS',(Date.now()-start)/1000)
  expect(answer).toContain('5')
  const result={realInference:true,networkDisabled:true,answer,seconds:(Date.now()-start)/1000}
  await dialog.getByRole('button',{name:'Cerrar asistente',exact:true}).click()
  await page.reload()
  await expect(page.locator('.library-open-button')).toContainText('privada')
  await page.getByRole('button',{name:'IA: opciones de reconocimiento',exact:true}).click()
  await page.getByRole('menuitem',{name:/Asistente de estudio local/}).click()
  dialog=page.getByRole('dialog',{name:'Asistente de estudio local'})
  await dialog.getByRole('button',{name:'Cargar IA guardada',exact:true}).click()
  await expect(dialog.getByRole('status')).toHaveText('IA lista',{timeout:90000})
  result.reloadOffline=true
  const base64=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=360;c.height=120;const ctx=c.getContext('2d');ctx.fillStyle='white';ctx.fillRect(0,0,c.width,c.height);ctx.font='bold 44px Arial';ctx.fillStyle='black';ctx.fillText('4 + 5 = ?',40,75);return c.toDataURL().split(',')[1]})
  await dialog.locator('input[type=file]').setInputFiles({name:'ejercicio.png',mimeType:'image/png',buffer:Buffer.from(base64,'base64')})
  await expect(dialog.getByRole('img',{name:'Imagen a consultar'})).toBeVisible()
  await dialog.getByRole('textbox',{name:'Pregunta al asistente'}).fill('Leé el cálculo de la imagen y decí el resultado. Una oración.')
  await dialog.getByRole('button',{name:'Preguntar',exact:true}).click()
  await expect(dialog.getByRole('button',{name:'Detener respuesta'})).toHaveCount(0,{timeout:180000})
  result.imageAnswer=await dialog.locator('.assistant-message.assistant .assistant-answer').last().innerText()
  console.log('ERROR IMAGEN',await dialog.getByRole('alert').allTextContents())
  console.log('IMAGEN',result.imageAnswer)
  expect(result.imageAnswer).toContain('9')
  for(const [subject,question,term] of [['bases','¿Para qué sirve SELECT en SQL? Una oración.','SELECT'],['programacion','¿Qué hace un bucle for en C++? Una oración.','bucle'],['programacion','Escribí una receta de pizza.','matemática']]){
    await dialog.getByRole('textbox',{name:'Pregunta al asistente'}).fill(question)
    await dialog.getByRole('button',{name:'Preguntar',exact:true}).click()
    await expect(dialog.getByRole('button',{name:'Detener respuesta'})).toHaveCount(0,{timeout:180000})
    const answer=await dialog.locator('.assistant-message.assistant .assistant-answer').last().innerText()
    console.log('CONSULTA',question,answer)
    expect(answer.toLowerCase()).toContain(term.toLowerCase())
    result[subject==='bases'?'sql':question.includes('pizza')?'outsideScope':'programming']=answer
  }
  await page.screenshot({path:'logs/asistente-real.png'})
  await writeFile('logs/asistente-real.json',JSON.stringify(result,null,2))
}finally{await context.close()}
